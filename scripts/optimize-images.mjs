/**
 * Generates AVIF + WebP variants for site imagery into src/assets/optimized/
 * and writes src/content/images.generated.ts (static imports for Vite).
 *
 *   node scripts/optimize-images.mjs
 *
 * Re-run whenever a source in src/assets/ is replaced (e.g. official scans).
 * Never upscales: widths above the source width are skipped.
 */
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";

const SRC = "src/assets";
const OUT = "src/assets/optimized";

// id → source file + target widths (CSS px × 1 and × 2 where the source allows)
const jobs = {
  cardRed: { file: "cards/ace-red.png", widths: [260, 520, 640] },
  cardBlack: { file: "cards/ace-black.png", widths: [260, 520, 640] },
  cardBlue: { file: "cards/ace-blue.png", widths: [260, 520, 640] },
  cardFan: { file: "brand/albastini-mark-official.png", widths: [300, 600, 1120] },
  boxSafari: { file: "box-safari-retail.webp", widths: [300, 600] },
  boxExpansion: { file: "box-expansion.webp", widths: [300, 600] },
  // Phase 4 — genuine source photography (derivatives documented in assets-source/phase4/DERIVATIVES.md)
  davidSanyaPortrait: {
    file: "photos/david-sanya-portrait.png",
    widths: [440, 880],
    q: { avif: 64, webp: 84 },
  },
  cardsOnTable: {
    file: "photos/cards-on-table.jpg",
    widths: [800, 1440, 2048],
    q: { avif: 58, webp: 80 },
  },
  cardFrontsOnWhite: {
    file: "photos/card-fronts-on-white.png",
    widths: [640, 1180],
    q: { avif: 64, webp: 84 },
  },
  // Final handoff — official brand mark (navbar/footer) and Tournament #26 champions
  brandMark: { file: "brand/albastini-mark-official.png", widths: [96, 192] },
  bedadiPortrait: {
    file: "photos/bedadi-portrait.jpg",
    widths: [480, 768],
    q: { avif: 64, webp: 84 },
  },
  mjeshiPortrait: {
    file: "photos/mjeshi-portrait.png",
    widths: [480, 830],
    q: { avif: 64, webp: 84 },
  },
  // Detail crops need a high-resolution source: the 600px box photo goes soft
  // when magnified, so no detail crop is generated from it. Example for later:
  //   boxDetail: { file: "photos/safari-box-hires.jpg", widths: [440, 880], crop: { left, top, width, height } },
  appHome: { file: "app-home-public.webp", widths: [250, 500] },
};

// Start clean so no stale derivative (e.g. an old crop of a person) survives.
await fs.rm(OUT, { recursive: true, force: true });
await fs.mkdir(OUT, { recursive: true });
const lines = ["// GENERATED by scripts/optimize-images.mjs — do not edit by hand.", ""];
const entries = [];

for (const [id, { file, widths, crop, q }] of Object.entries(jobs)) {
  const source = path.join(SRC, file);
  const input = crop ? await sharp(source).extract(crop).toBuffer() : source;
  const meta = await sharp(input).metadata();
  const usable = [
    ...new Set(
      widths
        .filter((w) => w <= meta.width)
        .concat(widths.some((w) => w > meta.width) ? [meta.width] : []),
    ),
  ].sort((a, b) => a - b);
  const variants = [];
  for (const w of usable) {
    const base = `${id}-${w}`;
    await sharp(input)
      .resize({ width: w })
      .avif({ quality: q?.avif ?? 55, effort: 6 })
      .toFile(path.join(OUT, `${base}.avif`));
    await sharp(input)
      .resize({ width: w })
      .webp({ quality: q?.webp ?? 80, effort: 6 })
      .toFile(path.join(OUT, `${base}.webp`));
    lines.push(`import ${id}${w}Avif from "@/assets/optimized/${base}.avif";`);
    lines.push(`import ${id}${w}Webp from "@/assets/optimized/${base}.webp";`);
    variants.push(w);
  }
  const h = Math.round((meta.height / meta.width) * 1000) / 1000;
  entries.push(
    `  ${id}: {\n    ratio: ${h},\n    width: ${meta.width},\n    avif: [${variants.map((w) => `[${id}${w}Avif, ${w}]`).join(", ")}],\n    webp: [${variants.map((w) => `[${id}${w}Webp, ${w}]`).join(", ")}],\n  },`,
  );
}

lines.push(
  "",
  "export type ImageSet = { ratio: number; width: number; avif: [string, number][]; webp: [string, number][] };",
  "",
  "export const images = {",
  ...entries,
  "} satisfies Record<string, ImageSet>;",
  "",
);
await fs.writeFile("src/content/images.generated.ts", lines.join("\n"));
console.log("ok:", Object.keys(jobs).join(", "));
