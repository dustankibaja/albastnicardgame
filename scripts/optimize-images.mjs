/**
 * Generates AVIF + WebP variants for site imagery into src/assets/optimized/
 * and writes src/content/images.generated.ts (static imports for Vite).
 *
 *   node scripts/optimize-images.mjs
 *
 * Re-run whenever a source in src/assets/ is replaced (e.g. official scans).
 * Never upscales: widths above the source width are skipped.
 */
import sharp from "sharp";
import fs from "node:fs/promises";
import path from "node:path";

const SRC = "src/assets";
const OUT = "src/assets/optimized";

// id → source file + target widths (CSS px × 1 and × 2 where the source allows)
const jobs = {
  cardRed: { file: "card-red-official.webp", widths: [240, 500] },
  cardBlack: { file: "card-black-official-v2.webp", widths: [240, 500] },
  cardBlue: { file: "card-blue-official.webp", widths: [240, 500] },
  cardFan: { file: "card-fan.webp", widths: [300, 600] },
  boxSafari: { file: "box-safari-retail.webp", widths: [300, 600] },
  boxExpansion: { file: "box-expansion.webp", widths: [300, 600] },
  appHome: { file: "app-home-public.webp", widths: [250, 500] },
};

await fs.mkdir(OUT, { recursive: true });
const lines = ["// GENERATED by scripts/optimize-images.mjs — do not edit by hand.", ""];
const entries = [];

for (const [id, { file, widths }] of Object.entries(jobs)) {
  const input = path.join(SRC, file);
  const meta = await sharp(input).metadata();
  const usable = [
    ...new Set(
      widths
        .filter((w) => w <= meta.width)
        .concat(widths.some((w) => w > meta.width) ? [meta.width] : []),
    ),
  ].sort((a, b) => a - b);
  const variants = [];
  for (const w of usable) {
    const base = `${id}-${w}`;
    await sharp(input)
      .resize({ width: w })
      .avif({ quality: 55, effort: 6 })
      .toFile(path.join(OUT, `${base}.avif`));
    await sharp(input)
      .resize({ width: w })
      .webp({ quality: 80, effort: 6 })
      .toFile(path.join(OUT, `${base}.webp`));
    lines.push(`import ${id}${w}Avif from "@/assets/optimized/${base}.avif";`);
    lines.push(`import ${id}${w}Webp from "@/assets/optimized/${base}.webp";`);
    variants.push(w);
  }
  const h = Math.round((meta.height / meta.width) * 1000) / 1000;
  entries.push(
    `  ${id}: {\n    ratio: ${h},\n    width: ${meta.width},\n    avif: [${variants.map((w) => `[${id}${w}Avif, ${w}]`).join(", ")}],\n    webp: [${variants.map((w) => `[${id}${w}Webp, ${w}]`).join(", ")}],\n  },`,
  );
}

lines.push(
  "",
  "export type ImageSet = { ratio: number; width: number; avif: [string, number][]; webp: [string, number][] };",
  "",
  "export const images = {",
  ...entries,
  "} satisfies Record<string, ImageSet>;",
  "",
);
await fs.writeFile("src/content/images.generated.ts", lines.join("\n"));
console.log("ok:", Object.keys(jobs).join(", "));
